    row = {'id': cid, 'text': text, 'kind': 'explicit', 'conditions': list(conditions),
           'exceptions': list(exceptions), 'concepts': labels, 'ambiguity_status': ambiguity,
           'review_note': f'语境：{context}。适用条件：' + ('；'.join(conditions) if conditions else '仅限本条表述的对象与来源语境') +
               f'。四轮复核：完整阅读问答及相邻段，按对象和完成状态原子化，对照既有命题与标准概念后逐条逆向核验；{check}。仅据固定汇编底本，不声称与原博客逐字校核。',
           'reviewer': REVIEWER, 'importance_level': level, 'importance_reason': reasons[level] + check,
           'evidence': citations, 'relations': []}
    if figure_note:
        row['figure_review_note'] = figure_note
